function fallbackDocDownload(htmlContent, filename) {
  var docHtml = '<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word" xmlns="http://www.w3.org/TR/REC-html40"><head><meta charset="utf-8"><title>Career Report</title></head><body>' + htmlContent + '</body></html>';
  var blob = new Blob([docHtml], { type: 'application/msword;charset=utf-8' });
  var url = URL.createObjectURL(blob);
  var a = document.createElement('a');
  a.href = url;
  a.download = filename + '.doc';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

window.handleCopyReport = function (e) {
  if (e && e.preventDefault) e.preventDefault();
  if (e && e.stopPropagation) e.stopPropagation();
  var pre = document.querySelector('#reportPreview pre');
  if (!pre) return;
  var txt = pre.textContent;

  var ta = document.createElement('textarea');
  ta.value = txt;
  ta.setAttribute('readonly', '');
  ta.style.position = 'absolute';
  ta.style.left = '-9999px';
  document.body.appendChild(ta);
  ta.select();
  try { ta.setSelectionRange(0, 999999); } catch (err) { }
  try { document.execCommand('copy'); } catch (err) { }
  if (ta.parentNode) document.body.removeChild(ta);

  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(txt).catch(function () { });
    }
  } catch (err) { }

  try { localStorage.setItem('Educator_Career_Report_Copied', txt); } catch (err) { }

  var btn = document.getElementById('copyReport');
  if (btn) {
    var oldText = btn.getAttribute('data-old') || btn.textContent;
    btn.setAttribute('data-old', oldText);
    btn.textContent = '✅ Copied!';
    btn.style.background = '#10b981';
    btn.style.borderColor = '#10b981';
    btn.style.color = '#fff';
    setTimeout(function () {
      btn.textContent = oldText;
      btn.style.background = '';
      btn.style.borderColor = '';
      btn.style.color = '';
    }, 2500);
  }
};

function copyReport() {
  window.handleCopyReport();
}

function exportRoadmapJSON() {
  var u = window.USER_DATA || { name: 'Student', role: 'Candidate', skills: [], experience: [] };
  var portalStatus = (u.officialPortal && u.officialPortal.verified) ? 'Verified Live Gateway' : 'Cached Client Data (Unverified Offline)';
  var payload = {
    app: 'Educator AI',
    version: '2.0.0',
    exportedAt: new Date().toISOString(),
    profile: u,
    hardwareTier: window.HARDWARE_TIER || 'workstation',
    officialPortalVerification: portalStatus
  };

  var dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(payload, null, 2));
  var downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute('download', 'EducatorAI_Roadmap_' + (u.role || 'Career').replace(/\s+/g, '_') + '.json');
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
  if (typeof window.showToast === 'function') {
    window.showToast('Career roadmap JSON exported successfully!');
  }
}

function shareRoadmapLink() {
  var u = window.USER_DATA || { role: 'Professional' };
  var shareText = 'Check out my verified career roadmap for ' + (u.role || 'Career Path') + ' generated by Educator AI: ' + window.location.href;

  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(shareText).then(function () {
      if (typeof window.showToast === 'function') window.showToast('Roadmap link copied to clipboard!');
    }).catch(function () {
      prompt('Copy your career roadmap link:', shareText);
    });
  } else {
    prompt('Copy your career roadmap link:', shareText);
  }
}

