/**
 * Educator AI Career Report & Export Service
 * Manages assessment report preview, DOC/PDF download, text copying,
 * JSON roadmap export, and shareable link generator.
 */

window.openReport = function () {
  var u = window.USER_DATA || { name: 'Alex Kadir', role: 'CS Graduate', skills: [], experience: [], education: [] };
  var d = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  var sk = (u.skills || []).join(', ') || '-';
  var ex = (u.experience || []).map(function (e) { return '- ' + e.title + ' at ' + e.company + ' (' + e.period + ')'; }).join('\n') || '-';
  var ed = (u.education || []).map(function (e) { return '- ' + e.degree + ' at ' + e.institution + ' (' + e.period + ')'; }).join('\n') || '-';
  var txt = 'CAREER ASSESSMENT REPORT\nGenerated by Educator AI Mentor - ' + d + '\n\nName: ' + u.name + '\nRole: ' + u.role + '\nEstimated Market Value: ' + (u.marketVal || '$78K') + '\n\nSKILLS\n' + sk + '\n\nEXPERIENCE\n' + ex + '\n\nEDUCATION\n' + ed + '\n\nTOP CAREER MATCHES\n' + (u.topMatches || []).map(function (m) { return '- ' + m.title + ' (' + m.match + ')'; }).join('\n') + '\n\nReport generated by Educator (Production Mentor System)';

  var pre = document.querySelector('#reportPreview pre');
  if (pre) pre.textContent = txt;
  var el = document.getElementById('reportOverlay');
  if (el) {
    el.style.display = 'flex';
    el.classList.add('active');
  }
  try {
    localStorage.setItem('Educator_Career_Report', txt);
    u.savedReport = txt;
    if (typeof window.saveUserData === 'function') window.saveUserData();
  } catch (e) { }
};

function openReport() {
  window.openReport();
}

window.handleCloseReport = function (e) {
  if (e && e.preventDefault) e.preventDefault();
  if (e && e.stopPropagation) e.stopPropagation();
  var el = document.getElementById('reportOverlay');
  if (el) {
    el.classList.remove('active');
    el.style.display = 'none';
  }
};

function closeReport() {
  window.handleCloseReport();
}

